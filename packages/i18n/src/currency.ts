export const DEFAULT_CURRENCY = "PHP";

export interface CurrencyOption {
  code: string;
  /** "PHP · Philippine peso". The English name comes from the runtime and is omitted when it has none. */
  label: string;
}

/** The picker's options, in code order. */
export function currencyOptions(): CurrencyOption[] {
  let names: Intl.DisplayNames | null = null;
  try {
    names = new Intl.DisplayNames(["en"], { type: "currency" });
  } catch {
    names = null;
  }
  return CURRENCY_CODES.map((code) => {
    const name = names?.of(code);
    return { code, label: name && name !== code ? `${code} · ${name}` : code };
  });
}
